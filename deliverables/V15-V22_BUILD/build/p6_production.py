def anchors_ok():
    bad = []
    for n in range(15, 23):
        ms = master_sentences(n)
        joined = " ".join(ms)
        for group, label in ((CAMERA[n], "camera"), (BROLL[n], "broll"),
                             (SOUND[n], "sound")):
            for trig, _ in group:
                if trig not in ms and trig not in joined:
                    bad.append((n, label, trig[:70]))
    return bad

if __name__ == "__main__":
    for n in range(15, 23):
        print("V%d  %d cards  %d camera  %d artifact  %d sound"
              % (n, len(FULLSCREEN[n]), len(CAMERA[n]), len(BROLL[n]), len(SOUND[n])))
    bad = anchors_ok()
    print("unanchored:", len(bad))
    for b in bad: print("   ", b)
